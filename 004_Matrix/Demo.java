        private static void printMatrix(int[][] matrix) {
                int rows = matrix.length;
                int cols = matrix[0].length;
                for (int i = 0; i < rows; i++) {
                        for (int j = 0; j < cols; j++)
                                System.out.print(matrix[i][j] + " ");
                        System.out.println();
                }
        }

